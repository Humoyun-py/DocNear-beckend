// Helper to generate dynamic multi-day schedules for any month
export function getDoctorScheduleForDate(dateStr: string, seed: number = 0): DaySchedule {
  const dateObj = new Date(dateStr);
  const dayOfWeek = dateObj.getDay(); // 0 is Sunday, 6 is Saturday
  const isSunday = dayOfWeek === 0;
  const isSaturday = dayOfWeek === 6;

  const dayNames = ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'];
  const monthNames = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
  const label = `${dayNames[dayOfWeek]} ${dateObj.getDate()} ${monthNames[dateObj.getMonth()]}`;

  const todayStr = new Date().toISOString().split('T')[0];
  const isToday = dateStr === todayStr;

  if (isSunday) {
    return {
      date: dateStr,
      dayLabel: label,
      isToday,
      slots: [
        { time: '10:00', isAvailable: seed % 2 === 0, period: 'morning' },
        { time: '11:30', isAvailable: true, period: 'morning' },
        { time: '14:00', isAvailable: false, period: 'afternoon' },
        { time: '15:30', isAvailable: seed % 3 !== 0, period: 'afternoon' },
      ],
    };
  }

  return {
    date: dateStr,
    dayLabel: label,
    isToday,
    slots: [
      { time: '09:00', isAvailable: (seed + dayOfWeek) % 2 === 0, period: 'morning' },
      { time: '09:30', isAvailable: true, period: 'morning' },
      { time: '10:15', isAvailable: (seed + dateObj.getDate()) % 3 !== 0, period: 'morning' },
      { time: '11:00', isAvailable: (seed + dateObj.getDate()) % 2 !== 0, period: 'morning' },
      { time: '11:45', isAvailable: false, period: 'morning' },
      { time: '13:00', isAvailable: true, period: 'afternoon' },
      { time: '14:00', isAvailable: (seed + dayOfWeek) % 3 === 0, period: 'afternoon' },
      { time: '14:45', isAvailable: true, period: 'afternoon' },
      { time: '15:30', isAvailable: true, period: 'afternoon' },
      { time: '16:15', isAvailable: (seed + dateObj.getDate()) % 2 === 0, period: 'afternoon' },
      { time: '17:00', isAvailable: !isSaturday, period: 'evening' },
      { time: '17:45', isAvailable: !isSaturday && (seed % 2 === 0), period: 'evening' },
      { time: '18:30', isAvailable: !isSaturday, period: 'evening' },
    ],
  };
}

// Helper to generate dynamic 7-day realistic schedules starting from today
function generateWeeklySchedule(): DaySchedule[] {
  return generateDynamicWeeklySchedule();
}

